#!/usr/bin/env python3
"""Safe netplan independence (preserve cloud-init YAML verbatim; no template rewrites)."""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterator, Optional

try:
    import yaml
except ImportError:  # pragma: no cover
    yaml = None  # type: ignore

DEST_NAME = "90-pveosi-static.yaml"
PROVENANCE_NAME = "pveosi-netplan-migration.json"
LOCK_NAME = ".netplan-migration.lock"
CLOUD_INIT_NAME_RE = re.compile(r"cloud[-_]?init", re.I)
PVEOSI_TMP_SUFFIX = ".pveosi-migrate.tmp"
PROVENANCE_REQUIRED_KEYS = (
    "version",
    "source_name",
    "source_sha256",
    "dest_name",
    "dest_sha256",
    "retired_name",
)


class NetplanSafetyError(Exception):
    """Netplan migration refused or failed (rollback attempted)."""


@dataclass(frozen=True)
class NetplanInspect:
    source_path: Path
    source_name: str
    dest_path: Path
    all_files: list[str]
    renderer: Optional[str]
    ethernet_count: int


@dataclass(frozen=True)
class NetplanPlan:
    inspect: Optional[NetplanInspect]
    action: str  # create_copy | already_migrated
    source_bytes: bytes


def _root() -> Path:
    return Path(os.environ.get("PVEOSI_GUEST_ROOT", "/"))


def netplan_dir() -> Path:
    return _root() / "etc/netplan"


def backup_dir() -> Path:
    return _root() / "var/lib/pveosi-guest-setup/backups"


def provenance_path() -> Path:
    return backup_dir() / PROVENANCE_NAME


def lock_path() -> Path:
    return backup_dir() / LOCK_NAME


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _safe_path_in_netplan(path: Path) -> None:
    if path.is_symlink():
        raise NetplanSafetyError(f"Refusing symlink in netplan path: {path.name}")
    try:
        resolved = path.resolve()
    except OSError as exc:
        raise NetplanSafetyError(f"Cannot resolve path: {path.name}") from exc
    base = netplan_dir().resolve()
    if not str(resolved).startswith(str(base) + os.sep) and resolved != base:
        raise NetplanSafetyError(f"Path escapes netplan directory: {path.name}")


def _safe_private_path(path: Path) -> None:
    if path.is_symlink():
        raise NetplanSafetyError(f"Refusing symlink: {path.name}")


def _load_yaml(text: str, label: str) -> dict[str, Any]:
    if yaml is None:
        raise NetplanSafetyError("python3-yaml is required for netplan safety checks.")
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise NetplanSafetyError(f"Invalid YAML in {label}.") from exc
    if data is None:
        data = {}
    if not isinstance(data, dict):
        raise NetplanSafetyError(f"Unexpected YAML structure in {label}.")
    return data


def _network_block(doc: dict[str, Any]) -> dict[str, Any]:
    net = doc.get("network")
    if net is None:
        return {}
    if not isinstance(net, dict):
        raise NetplanSafetyError("Invalid network: block in netplan YAML.")
    return net


def _inspect_structure(net: dict[str, Any], label: str) -> tuple[int, Optional[str]]:
    for risky in ("bonds", "bridges", "vlans", "vrfs", "dummy-devices", "modems"):
        if risky in net and net[risky]:
            raise NetplanSafetyError(
                f"{label} uses {risky}; automatic preservation is not supported."
            )
    renderer = net.get("renderer")
    eth = net.get("ethernets", {}) or {}
    if not isinstance(eth, dict):
        raise NetplanSafetyError("Invalid ethernets block in netplan YAML.")
    count = len(eth)
    if count == 0:
        raise NetplanSafetyError("No ethernet interfaces found in cloud-init netplan.")
    if count > 1:
        raise NetplanSafetyError(
            "Multiple ethernet interfaces; cannot preserve safely in this release."
        )
    return count, renderer if isinstance(renderer, str) else None


def list_netplan_files() -> list[Path]:
    np = netplan_dir()
    if not np.is_dir():
        raise NetplanSafetyError("No /etc/netplan directory.")
    files = sorted(p for p in np.glob("*.yaml") if p.is_file())
    for p in files:
        _safe_path_in_netplan(p)
    return files


def _identify_cloud_init_source(files: list[Path]) -> Path:
    matches: list[Path] = []
    for p in files:
        if p.name == DEST_NAME:
            continue
        if CLOUD_INIT_NAME_RE.search(p.name):
            matches.append(p)
            continue
        text = p.read_text(encoding="utf-8")
        if "generated by cloud-init" in text.lower() or "cloud-init" in text.lower()[:200]:
            matches.append(p)
    if not matches:
        raise NetplanSafetyError(
            "No cloud-init netplan file found (expected e.g. 50-cloud-init.yaml)."
        )
    if len(matches) > 1:
        raise NetplanSafetyError(
            "Multiple cloud-init netplan candidates; resolve manually before using this tool."
        )
    for p in files:
        if p == matches[0] or p.name == DEST_NAME:
            continue
        doc = _load_yaml(p.read_text(encoding="utf-8"), p.name)
        if _network_block(doc).get("ethernets"):
            raise NetplanSafetyError(
                f"Conflicting netplan files with ethernet definitions: {p.name}"
            )
    return matches[0]


def inspect_netplan() -> NetplanInspect:
    files = list_netplan_files()
    dest = netplan_dir() / DEST_NAME
    _safe_path_in_netplan(dest)
    source = _identify_cloud_init_source(files)
    text = source.read_text(encoding="utf-8")
    net = _network_block(_load_yaml(text, source.name))
    eth_count, renderer = _inspect_structure(net, source.name)
    return NetplanInspect(
        source_path=source,
        source_name=source.name,
        dest_path=dest,
        all_files=[p.name for p in files],
        renderer=renderer,
        ethernet_count=eth_count,
    )


def _validate_provenance_record(data: dict[str, Any]) -> None:
    if data.get("version") != 1:
        raise NetplanSafetyError("Invalid netplan migration provenance version.")
    for key in PROVENANCE_REQUIRED_KEYS:
        if not data.get(key):
            raise NetplanSafetyError(f"Invalid netplan migration provenance (missing {key}).")
    if data.get("dest_name") != DEST_NAME:
        raise NetplanSafetyError("Invalid netplan migration provenance dest_name.")


def read_provenance() -> Optional[dict[str, Any]]:
    path = provenance_path()
    if not path.is_file():
        return None
    _safe_private_path(path)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise NetplanSafetyError("Corrupt netplan migration provenance.") from exc
    if not isinstance(data, dict):
        raise NetplanSafetyError("Invalid netplan migration provenance.")
    _validate_provenance_record(data)
    return data


def provenance_fingerprint() -> Optional[str]:
    prov = read_provenance()
    if not prov:
        return None
    dest = netplan_dir() / DEST_NAME
    if not dest.is_file():
        return None
    payload = {
        "dest_sha256": prov.get("dest_sha256"),
        "source_sha256": prov.get("source_sha256"),
        "retired_name": prov.get("retired_name"),
        "dest_file_sha256": _sha256_file(dest),
    }
    return _sha256_bytes(json.dumps(payload, sort_keys=True).encode("utf-8"))


def detect_interrupted_transactions() -> list[str]:
    issues: list[str] = []
    np = netplan_dir()
    if np.is_dir():
        for p in np.glob(f"*{PVEOSI_TMP_SUFFIX}"):
            if p.exists():
                issues.append(f"Interrupted netplan transaction: {p.name}")
    bdir = backup_dir()
    if bdir.is_dir():
        dest = np / DEST_NAME if np.is_dir() else None
        prov = provenance_path()
        retired = list(bdir.glob("*.retired"))
        if dest and dest.is_file() and not prov.is_file() and retired:
            issues.append("Netplan source retired but provenance not written.")
        if prov.is_file() and dest and not dest.is_file():
            issues.append("Provenance present but destination netplan file missing.")
    return issues


def _write_provenance_new(data: dict[str, Any]) -> None:
    path = provenance_path()
    if path.exists():
        raise NetplanSafetyError("Provenance file already exists; refusing overwrite.")
    _validate_provenance_record(data)
    payload = (json.dumps(data, indent=2) + "\n").encode("utf-8")
    _atomic_write_private(path, payload, create_only=True)


def _atomic_write_private(path: Path, data: bytes, create_only: bool = False) -> None:
    parent = path.parent
    parent.mkdir(parents=True, exist_ok=True)
    if parent.stat().st_mode & 0o077:
        os.chmod(parent, 0o700)
    if path.exists():
        if create_only:
            raise NetplanSafetyError(f"Refusing to overwrite existing file: {path.name}")
        if path.parent == netplan_dir():
            _safe_path_in_netplan(path)
        else:
            _safe_private_path(path)
    tmp = path.with_name(path.name + PVEOSI_TMP_SUFFIX)
    if tmp.exists():
        raise NetplanSafetyError(
            f"Interrupted transaction (temporary file {tmp.name} present); resolve manually."
        )
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        os.write(fd, data)
    finally:
        os.close(fd)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)
    os.chmod(path, 0o600)


@contextmanager
def migration_lock() -> Iterator[None]:
    bdir = backup_dir()
    bdir.mkdir(parents=True, exist_ok=True)
    os.chmod(bdir, 0o700)
    lock = lock_path()
    if lock.exists():
        raise NetplanSafetyError("Another netplan migration appears in progress.")
    fd = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    os.write(fd, str(os.getpid()).encode("ascii"))
    os.close(fd)
    try:
        yield
    finally:
        try:
            lock.unlink(missing_ok=True)
        except OSError:
            pass


def migration_state() -> str:
    """Return: needs_migration | already_migrated | user_managed_dest | inconsistent."""
    for issue in detect_interrupted_transactions():
        raise NetplanSafetyError(issue)
    dest = netplan_dir() / DEST_NAME
    if dest.exists():
        _safe_path_in_netplan(dest)
    prov = read_provenance()
    files = list_netplan_files() if netplan_dir().is_dir() else []
    names = {p.name for p in files}
    has_dest = dest.is_file() and not dest.is_symlink()
    has_source_candidate = any(
        CLOUD_INIT_NAME_RE.search(n) for n in names if n != DEST_NAME
    ) or any(
        n != DEST_NAME
        and "cloud-init" in (netplan_dir() / n).read_text(encoding="utf-8").lower()[:200]
        for n in names
        if (netplan_dir() / n).is_file()
    )

    if prov:
        retired = backup_dir() / str(prov.get("retired_name", ""))
        _safe_private_path(retired)
        expected_hash = str(prov.get("dest_sha256", ""))
        if not has_dest:
            return "inconsistent"
        if _sha256_file(dest) != expected_hash:
            return "inconsistent"
        backup_src = backup_dir() / str(prov.get("source_name", ""))
        if backup_src.is_file() and _sha256_file(backup_src) != str(prov.get("source_sha256", "")):
            return "inconsistent"
        if has_source_candidate:
            return "inconsistent"
        if not retired.is_file():
            return "inconsistent"
        return "already_migrated"

    if has_dest:
        return "user_managed_dest"
    if has_source_candidate or any(n != DEST_NAME for n in names):
        try:
            _identify_cloud_init_source(files)
            return "needs_migration"
        except NetplanSafetyError:
            return "inconsistent"
    return "needs_migration"


def build_netplan_plan() -> NetplanPlan:
    if yaml is None:
        raise NetplanSafetyError("python3-yaml is required before netplan changes.")
    state = migration_state()
    dest = netplan_dir() / DEST_NAME
    if state == "already_migrated":
        return NetplanPlan(
            inspect=None,
            action="already_migrated",
            source_bytes=dest.read_bytes(),
        )
    if state == "user_managed_dest":
        raise NetplanSafetyError(
            f"{DEST_NAME} exists without pveosi migration provenance; treat as user-managed."
        )
    if state == "inconsistent":
        raise NetplanSafetyError(
            "Netplan migration state is inconsistent; inspect backups and /etc/netplan manually."
        )
    info = inspect_netplan()
    source_bytes = info.source_path.read_bytes()
    if dest.exists():
        raise NetplanSafetyError(f"Refusing to overwrite existing {DEST_NAME}.")
    return NetplanPlan(info, "create_copy", source_bytes)


def netplan_get_effective() -> str:
    if os.environ.get("PVEOSI_GUEST_MOCK_CMD") == "1":
        mock = os.environ.get("PVEOSI_GUEST_MOCK_NETPLAN_GET", "")
        if mock.startswith("file:"):
            return Path(mock[5:]).read_text(encoding="utf-8")
        return mock
    r = subprocess.run(["netplan", "get"], capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise NetplanSafetyError("netplan get failed; cannot verify effective configuration.")
    return r.stdout


def netplan_generate_validate() -> None:
    if os.environ.get("PVEOSI_GUEST_MOCK_CMD") == "1":
        if os.environ.get("PVEOSI_GUEST_MOCK_NETPLAN_GENERATE_FAIL") == "1":
            raise NetplanSafetyError("netplan generate validation failed (mock).")
        return
    r = subprocess.run(["netplan", "generate"], capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise NetplanSafetyError("netplan generate failed.")


def _hash_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _normalize_effective(text: str) -> str:
    lines = [ln.rstrip() for ln in text.splitlines() if ln.strip()]
    return "\n".join(lines)


def _rollback_migration(dest: Path, source: Path, retired: Path) -> None:
    if dest.exists() and dest.is_file():
        dest.unlink()
    if not source.exists() and retired.is_file():
        shutil.move(str(retired), str(source))


def migrate_netplan_independence(dry_run: bool = False) -> dict[str, str]:
    plan = build_netplan_plan()
    if plan.action == "already_migrated":
        return {"status": "already_migrated", "dest": DEST_NAME}
    if dry_run:
        assert plan.inspect
        return {
            "status": "would_migrate",
            "source": plan.inspect.source_name,
            "dest": DEST_NAME,
            "bytes": str(len(plan.source_bytes)),
        }

    with migration_lock():
        assert plan.inspect
        info = plan.inspect
        source = info.source_path
        dest = info.dest_path
        before = netplan_get_effective()
        bdir = backup_dir()
        bdir.mkdir(parents=True, exist_ok=True)
        os.chmod(bdir, 0o700)

        backup_copy = bdir / source.name
        if backup_copy.exists():
            if _sha256_file(backup_copy) != _sha256_bytes(plan.source_bytes):
                raise NetplanSafetyError(
                    f"Backup {backup_copy.name} exists with different content; refusing."
                )
        else:
            shutil.copy2(source, backup_copy)
            os.chmod(backup_copy, 0o600)

        retired = bdir / f"{source.name}.retired"
        try:
            _atomic_write_private(dest, plan.source_bytes, create_only=True)
            shutil.move(str(source), str(retired))
            os.chmod(retired, 0o600)
            netplan_generate_validate()
            after = netplan_get_effective()
            if _hash_text(_normalize_effective(before)) != _hash_text(_normalize_effective(after)):
                raise NetplanSafetyError("Effective netplan configuration changed after migration.")
            prov = {
                "version": 1,
                "source_name": source.name,
                "source_sha256": _sha256_bytes(plan.source_bytes),
                "dest_name": DEST_NAME,
                "dest_sha256": _sha256_bytes(plan.source_bytes),
                "retired_name": retired.name,
                "migrated_at": int(time.time()),
            }
            _write_provenance_new(prov)
        except NetplanSafetyError:
            _rollback_migration(dest, source, retired)
            raise

    return {
        "status": "migrated",
        "source": info.source_name,
        "dest": DEST_NAME,
        "effective_hash": _hash_text(_normalize_effective(after)),
    }


def independent_netplan_verified() -> bool:
    try:
        return migration_state() == "already_migrated"
    except NetplanSafetyError:
        return False


def network_diagnostics_readonly(backend: str) -> str:
    lines = [f"Network backend: {backend}", "Read-only diagnostics (no changes applied):"]
    if backend == "netplan":
        try:
            ms = migration_state()
            lines.append(f"  migration state: {ms}")
            info = inspect_netplan() if ms == "needs_migration" else None
            if info:
                lines.append(f"  cloud-init source: {info.source_name}")
            lines.append(
                f"  {DEST_NAME}: {'present' if (netplan_dir() / DEST_NAME).exists() else 'absent'}"
            )
        except NetplanSafetyError as exc:
            lines.append(f"  netplan inspect: {exc}")
    elif backend == "ifupdown":
        iface = _root() / "etc/network/interfaces"
        lines.append(iface.read_text(encoding="utf-8")[:4000] if iface.is_file() else "  missing")
    elif backend == "systemd-networkd":
        nd = _root() / "etc/systemd/network"
        for p in sorted(nd.glob("*.network"))[:20]:
            lines.append(f"--- {p.name} ---")
            lines.append(p.read_text(encoding="utf-8")[:2000])
    lines.append(
        "  Note: ifupdown/systemd-networkd guests require manual network verification."
    )
    return "\n".join(lines)
